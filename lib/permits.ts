const decode = (c: string): Requirement =>
  c === "R" ? "required" : c === "T" ? "ticket" : "not-required";

const slug = (s: string) =>
  s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");

export const PERMITS: PermitEntry[] = STATES.flatMap((state) =>
  RAW[state].map(([name, code], i) => ({
    id: `${slug(state)}-${i + 1}-${slug(name)}`,
    state,
    no: i + 1,
    name,
    mgp: decode(code[0]),
    permit: decode(code[1]),
  })),
);

